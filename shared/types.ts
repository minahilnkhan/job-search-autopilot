// Types shared by the server and the web app. Keep this file dependency-free.

export type Severity = "fail" | "warn";

export type FilterReason = {
  code: string; // stable machine code, e.g. "experience_4plus"
  severity: Severity;
  message: string; // what the UI shows
  evidence?: string; // the JD snippet that triggered it, when there is one
};

export type SponsorshipStated = "yes" | "no" | "unstated";
export type EVerify = "confirmed" | "likely" | "unknown";
export type AtsType = "greenhouse" | "lever" | "ashby" | "other";
export type Tier = "A" | "B" | "skip";
export type JobStatus = "new" | "shortlisted" | "dismissed";

export type EmploymentFlags = {
  w1099: boolean;
  c2c: boolean;
  freelance: boolean;
  unpaid: boolean;
  commissionOnly: boolean;
  contract: boolean;
  contractToHire: boolean;
  staffingAgency: boolean;
  partTime: boolean;
};

/** Fields pulled out of a JD by regex. The user reviews and can edit every one. */
export type ExtractedFields = {
  yearsRequired: number | null;
  remote: boolean;
  remoteCountryStated: boolean;
  sponsorshipStated: SponsorshipStated;
  employment: EmploymentFlags;
  requiresClearance: boolean;
  requiresCitizenship: boolean;
  /** The JD says the employer participates in E-Verify (a hint; you still confirm per company). */
  eVerifyMentioned: boolean;
  /** Snippet of JD text behind each detected field, keyed by field name. */
  evidence: Record<string, string>;
};

export type Company = {
  id: number;
  name: string;
  website: string | null;
  atsType: AtsType | null;
  atsBoardToken: string | null;
  eVerify: EVerify;
  h1bHistory: number | null;
  tags: string[];
  warmContact: boolean;
  notes: string | null;
};

export type Job = {
  id: number;
  companyId: number;
  companyName: string;
  title: string;
  url: string | null;
  location: string | null;
  remote: boolean;
  postedAt: string | null;
  description: string;
  source: string;
  yearsRequired: number | null;
  sponsorshipStated: SponsorshipStated;
  hardFilterPass: boolean;
  filterReasons: FilterReason[];
  extractedFields: ExtractedFields;
  fitScore: number | null;
  tier: Tier | null;
  status: JobStatus;
  createdAt: number;
};

/** Body for POST /api/jobs/extract */
export type ExtractRequest = {
  title: string;
  location?: string;
  description: string;
};

/** Body for POST /api/jobs */
export type CreateJobRequest = {
  companyName: string;
  title: string;
  url?: string;
  location?: string;
  postedAt?: string;
  description: string;
  /** The reviewed fields. Omit to use raw extraction. */
  fields?: ExtractedFields;
};

export type CreateJobResponse = { duplicate: boolean; job: Job };

export type Settings = {
  targets: {
    appsPerDay: number;
    daysPerWeek: number;
    hoursPerWeekCap: number;
    bucketHours: { applications: number; projects: number; prep: number };
  };
  capReviewDate: string; // YYYY-MM-DD
  /** Fixed answers. Never generated by the LLM. */
  workAuth: {
    authorizedToWorkInUS: "Yes" | "No";
    requiresSponsorshipNowOrFuture: "Yes" | "No";
  };
  locationPrefs: { preferred: string[]; openToRelocation: boolean };
  models: { scoring: string; tailoring: string; checkIns: string };
};
