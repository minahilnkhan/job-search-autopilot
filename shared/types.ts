// Types shared by the server and the web app. Keep this file dependency-free.

export type Severity = "fail" | "warn";

export type FilterReason = {
  code: string; // stable machine code, e.g. "experience_4plus"
  severity: Severity;
  message: string; // what the UI shows
  evidence?: string; // the JD snippet that triggered it, when there is one
};

export type SponsorshipStated = "yes" | "no" | "unstated";
export type EVerify = "confirmed" | "likely" | "unknown";
export type AtsType = "greenhouse" | "lever" | "ashby" | "other";
export type Tier = "A" | "B" | "skip";
export type JobStatus = "new" | "shortlisted" | "dismissed";

export type EmploymentFlags = {
  w1099: boolean;
  c2c: boolean;
  freelance: boolean;
  unpaid: boolean;
  commissionOnly: boolean;
  contract: boolean;
  contractToHire: boolean;
  staffingAgency: boolean;
  partTime: boolean;
};

/** Fields pulled out of a JD by regex. The user reviews and can edit every one. */
export type ExtractedFields = {
  yearsRequired: number | null;
  remote: boolean;
  remoteCountryStated: boolean;
  sponsorshipStated: SponsorshipStated;
  employment: EmploymentFlags;
  requiresClearance: boolean;
  requiresCitizenship: boolean;
  /** The JD says the employer participates in E-Verify (a hint; you still confirm per company). */
  eVerifyMentioned: boolean;
  /** Snippet of JD text behind each detected field, keyed by field name. */
  evidence: Record<string, string>;
};

export type Company = {
  id: number;
  name: string;
  website: string | null;
  atsType: AtsType | null;
  atsBoardToken: string | null;
  eVerify: EVerify;
  h1bHistory: number | null;
  tags: string[];
  warmContact: boolean;
  notes: string | null;
  atsLastCheckedAt: string | null; // ISO; when the job board was last fetched
  atsLastStatus: string | null; // e.g. "ok: 121 postings" or the fetch error
};

export type Job = {
  id: number;
  companyId: number;
  companyName: string;
  title: string;
  url: string | null;
  location: string | null;
  remote: boolean;
  postedAt: string | null;
  description: string;
  source: string;
  yearsRequired: number | null;
  sponsorshipStated: SponsorshipStated;
  hardFilterPass: boolean;
  filterReasons: FilterReason[];
  extractedFields: ExtractedFields;
  fitScore: number | null;
  scoreBreakdown: ScoreBreakdown | null;
  redFlags: string[];
  tier: Tier | null;
  scoredAt: number | null;
  externalId: string | null;
  status: JobStatus;
  createdAt: number;
};

/** GET /api/jobs leaves out descriptions; GET /api/jobs/:id has the full job. */
export type JobListItem = Omit<Job, "description">;

/** Body for POST /api/jobs/extract */
export type ExtractRequest = {
  title: string;
  location?: string;
  description: string;
};

/** Body for POST /api/jobs */
export type CreateJobRequest = {
  companyName: string;
  title: string;
  url?: string;
  location?: string;
  postedAt?: string;
  description: string;
  /** The reviewed fields. Omit to use raw extraction. */
  fields?: ExtractedFields;
};

export type CreateJobResponse = { duplicate: boolean; job: Job };

export type Settings = {
  targets: {
    appsPerDay: number;
    daysPerWeek: number;
    hoursPerWeekCap: number;
    bucketHours: { applications: number; projects: number; prep: number };
  };
  capReviewDate: string; // YYYY-MM-DD
  /** Fixed answers. Never generated by the LLM. */
  workAuth: {
    authorizedToWorkInUS: "Yes" | "No";
    requiresSponsorshipNowOrFuture: "Yes" | "No";
  };
  locationPrefs: { preferred: string[]; openToRelocation: boolean };
  models: { scoring: string; tailoring: string; checkIns: string };
  /** What makes Today's picks. Only applies to ranking; scoring is unchanged. */
  /** Your own answers to common application questions, reused as-is (never AI-written). */
  standardAnswers: { question: string; answer: string }[];
  shortlist: {
    tierAPicks: number; // how many Tier A (8–10) jobs in today's deck
    tierBPicks: number; // how many Tier B (5–7) jobs in today's deck
    maxAgeDays: number; // postings older than this never make Today's picks
    preferredCityBoost: number; // extra ranking points for jobs in a preferred city (Chicago)
  };
  pipeline: {
    enabled: boolean;
    dailyTime: string; // "HH:MM", 24-hour
    timezone: string; // IANA, e.g. "America/Chicago"
    maxScoresPerRun: number;
  };
};

// ---- Phase 2: scoring and shortlist -----------------------------------------

export type RequirementCheck = {
  requirement: string;
  met: "yes" | "partial" | "no";
  /** The inventory fact that shows it's met. A "yes" without one is downgraded to "partial". */
  evidence: string;
};

/** Mentor-prompt rubric. The AI fills in the judgments; code does the arithmetic. */
export type ScoreBreakdown = {
  requirements: RequirementCheck[];
  requirementsMatch: number; // 0–4, computed from requirements
  roleSignal: number; // 0–2
  roleSignalReason: string;
  stackMatch: number; // 0–2
  stackMatchReason: string;
  strategicBonus: number; // 0–2, computed from company facts
  strategicReasons: string[];
  total: number; // 1–10
  tierCap: string | null; // why the tier was capped, e.g. no sponsorship
  whyFits: string;
  gaps: string[];
  model: string;
};

export type RunStats = {
  companies: number;
  companiesFailed: number;
  postingsSeen: number;
  newJobs: number;
  passedFilters: number;
  scored: number;
  scoreErrors: number;
  skippedStale: number; // passed the filters but posted 30+ days ago, so not scored
  skippedOverCap: number;
  shortlisted: number;
  costUsd: number;
};

export type PipelineRun = {
  id: number;
  trigger: "schedule" | "catch_up" | "manual";
  startedAt: number;
  finishedAt: number | null;
  status: "running" | "ok" | "partial" | "failed";
  stats: RunStats | null;
  message: string | null;
};

/** Live state of the run in progress (GET /api/pipeline/runs). */
export type PipelineProgress = {
  phase: "fetching" | "scoring";
  companiesDone: number;
  companiesTotal: number;
  scored: number;
  toScore: number;
  costUsd: number;
  stopRequested: boolean;
};

export type ShortlistEntry = { rank: number; job: Job; eVerify: EVerify; warmContact: boolean };
export type Shortlist = { date: string; run: PipelineRun | null; entries: ShortlistEntry[] };

// ---- Phase 3: resumes, Truth Check, applications -----------------------------

export type ResumeEntry = {
  org: string;
  location: string | null;
  role: string | null;
  dates: string | null;
  bullets: string[];
};
export type ResumeSection = { title: string; entries: ResumeEntry[]; lines: string[] };
export type ResumeContent = { name: string; contact: string; sections: ResumeSection[] };
export type BaseType = "fde" | "swe";

/** One changed line in a tailored resume, shown as before → after. */
export type ResumeChange = { id: string; where: string; before: string; after: string; reason: string };

export type TruthIssueKind = "unverified_number" | "do_not_claim" | "ownership" | "placeholder" | "length" | "banned_word" | "render";
export type TruthIssue = {
  kind: TruthIssueKind;
  severity: "fail" | "warn";
  where: string; // e.g. "Resume › Experience › Yabla › bullet 2", "Recruiter note"
  text: string; // the offending line
  message: string; // why, in plain words
  lineId?: string; // resume line id, so the UI can jump to it
};
export type TruthReport = { pass: boolean; issues: TruthIssue[]; checkedAt: number };

export type Answer = { question: string; answer: string; source: "fixed" | "standard" | "generated" };

export type ApplicationStatus =
  | "draft"
  | "ready_for_review"
  | "approved"
  | "submitted"
  | "screen"
  | "interview"
  | "offer"
  | "rejected"
  | "ghosted"
  | "withdrawn";

export type ApplicationSummary = {
  id: number;
  jobId: number;
  jobTitle: string;
  companyName: string;
  tier: "A" | "B" | null;
  fitScore: number | null;
  status: ApplicationStatus;
  truthPass: boolean;
  truthOverride: { reason: string; at: number } | null;
  failCount: number;
  snoozedUntil: string | null;
  createdAt: number;
};

export type ApplicationDetail = ApplicationSummary & {
  job: Job;
  baseType: BaseType;
  resume: ResumeContent;
  resumeText: string;
  changes: ResumeChange[];
  recruiterNote: string | null;
  answers: Answer[];
  truth: TruthReport;
  pdfPages: number | null;
  hasPdf: boolean;
  hasDocx: boolean;
  prepNotes: string[];
  reviewReason: string | null; // why you rejected it
  tailoring: { keywordsCovered: string[]; keywordsMissing: string[]; honestGaps: string[] } | null;
};

export type BaseResume = {
  baseType: BaseType;
  id: number | null;
  text: string;
  truth: TruthReport | null;
  pdfPages: number | null;
  hasPdf: boolean;
};
